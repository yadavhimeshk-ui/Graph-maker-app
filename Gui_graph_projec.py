def graphp():
    x_data = [float(i) for i in x.get().split(",")]
    y_data = [float(j) for j in y.get().split(",")]
    plt.figure(figsize=(10,6))
    plt.plot(x_data, y_data)
    plt.xlabel(f"{xlabel.get()}".upper())
    plt.ylabel(f"{ylabel.get()}".upper())
    plt.title(f"{title.get()}")
    plt.grid(False)
    plt.tight_layout()
    plt.show()
def graphb():
    x_data = [float(i) for i in x.get().split(",")]
    y_data = [float(j) for j in y.get().split(",")]
    plt.figure(figsize=(10,6))
    plt.bar(x_data, y_data)
    plt.xlabel(f"{xlabel.get()}".upper())
    plt.ylabel(f"{ylabel.get()}".upper())
    plt.title(f"{title.get()}")
    plt.grid(False)
    plt.tight_layout()
    plt.show()
