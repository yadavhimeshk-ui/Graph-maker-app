# code for clear the input and output where used .delete(0, tk.END) function and for matplotlib used close("all") function
def clear_all():
    x.delete(0, tk.END)
    y.delete(0, tk.END)
    xlabel.delete(0, tk.END)
    ylabel.delete(0, tk.END)
    title.delete(0, tk.END)
    plt.close('all')
# code for exit the program
def exit_app():
    root.destroy()
btn_frame = tk.Frame(root, bg="green")
btn_frame.pack(pady=15)
btn_frame1 = tk.Frame(root, bg="green")
btn_frame1.pack(pady=15)
clear_btn = tk.Button(btn_frame, text="Clear", width=10, command=clear_all)
clear_btn.grid(row=0, column=1, padx=5) # grid function is used to align the buttons therefor in program both clear and exit button are in one line
exit_btn = tk.Button(btn_frame, text="Exit", width=10, command=exit_app)
exit_btn.grid(row=0, column=2, padx=5)
button1 = tk.Button(btn_frame1, text="Plot line graph",command=graphp)
button1.grid(row=1, column=1, padx=5)
button2 = tk.Button(btn_frame1, text="Plot bar graph",command=graphb)
button2.grid(row=1, column=2, padx=5)
